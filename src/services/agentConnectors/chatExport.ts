/**
 * The "vault map" file a person uploads to a chat project (Claude, ChatGPT, Gemini). Pure.
 *
 * It is built from the same projection the agent index uses (`includedRecords`), so the one scope
 * function decides which notes appear: excluded, protected and hidden folders never do. It lists
 * paths, tags and link targets and never any note body. Deterministic: the same records give the
 * same bytes (the only changing line is `generatedAt` in the header, which is passed in).
 */
import { includedRecords, type ProjectionScope, type RawRecord } from '../agentIndex/agentIndexProjection';

/**
 * What a chat assistant is told about the map. It never names an excluded or protected folder: the
 * file is uploaded, and a folder name is itself something the owner may not want to share.
 */
export const CHAT_EXPORT_INSTRUCTIONS = [
    '## How to use this map',
    '',
    '- Each line below is one note: its path, its tags and the notes it links to.',
    '- Use it to work out which notes matter for a question. It has no note text.',
    '- Ask the owner to paste a note when you need what it says.',
    '',
].join('\n');

/** First line of every file we write, so a later export replaces only our own earlier files. */
export const CHAT_EXPORT_MARKER = '<!-- ai-organiser/chat-project-export -->';
export const CHAT_EXPORT_BASENAME = 'AI Organiser vault map';

/** A per-file size we choose ourselves; it is not a vendor limit. */
export const CHAT_EXPORT_PART_BYTES = 400 * 1024;

/** Matches the names this feature writes: the single file or one of its numbered parts. */
export const CHAT_EXPORT_NAME_PATTERN = /^AI Organiser vault map( \(part \d+ of \d+\))?\.md$/;

export interface ChatExportInput {
    records: readonly RawRecord[];
    scope: ProjectionScope;
    /** The agent-neutral instructions text (exactly what "Copy agent instructions" copies) */
    instructions: string;
    generatedAt: string;
}

export interface ChatExportPart {
    name: string;
    text: string;
}

export interface ChatExportResult {
    parts: ChatExportPart[];
    notes: number;
}

const LINE_SEPARATORS = new RegExp(`[\\r\\n${String.fromCharCode(0x2028)}${String.fromCharCode(0x2029)}]+`, 'g');
const oneLine = (s: string): string => s.replace(LINE_SEPARATORS, ' ').replace(/\|/g, '\\|').trim();
const bytesOf = (s: string): number => new TextEncoder().encode(s).length;

function noteLine(record: RawRecord, scope: ProjectionScope): string {
    const fields = [`- ${oneLine(record.path)}`];
    const tags = [...new Set(record.tags)].sort();
    if (tags.length > 0) fields.push(`tags: ${tags.map(oneLine).join(', ')}`);
    if (scope.includeAliases && record.aliases.length > 0) fields.push(`aliases: ${[...new Set(record.aliases)].sort().map(oneLine).join(', ')}`);
    if (scope.includeHeadings && record.headings.length > 0) fields.push(`headings: ${record.headings.map(oneLine).join(' / ')}`);
    const links: string[] = [];
    let excludedLinks = 0;
    for (const link of record.links) {
        if (link.target === null) {
            if (scope.exportUnresolvedLinks) links.push(`?${oneLine(link.text)}`);
        } else if (scope.isIncluded(link.target)) {
            links.push(oneLine(link.target));
        } else {
            excludedLinks++;
        }
    }
    const uniqueLinks = [...new Set(links)].sort();
    if (uniqueLinks.length > 0) fields.push(`links: ${uniqueLinks.join(', ')}`);
    if (excludedLinks > 0) fields.push('links to excluded notes: [excluded]');
    return fields.join(' | ');
}

function header(part: number, total: number, generatedAt: string, notes: number, instructions: string): string {
    const lines = [
        CHAT_EXPORT_MARKER,
        `# Vault map${total > 1 ? ` (part ${part} of ${total})` : ''}`,
        '',
        `Generated by AI Organiser at ${generatedAt}. ${notes} notes are listed.`,
        '',
        'This file lists note paths, tags and link targets only. It contains no note text. Notes the owner excluded are not listed.',
        '',
    ];
    if (part === 1) lines.push(instructions.replace(/\n+$/, ''), '');
    lines.push('## Notes', '');
    return lines.join('\n');
}

/** A single note line never exceeds this, so one huge record cannot push a part over its size. */
export const CHAT_EXPORT_MAX_LINE_BYTES = 4096;

/** Cut a line to the byte limit at a character boundary, marking the cut. */
function capLine(line: string): string {
    if (bytesOf(line) <= CHAT_EXPORT_MAX_LINE_BYTES) return line;
    let out = '';
    let used = 0;
    for (const ch of line) {
        const n = bytesOf(ch);
        if (used + n > CHAT_EXPORT_MAX_LINE_BYTES - 3) break;
        out += ch;
        used += n;
    }
    return `${out}…`;
}

/** Greedy split with the exact header bytes of each part, for a given total part count. */
function split(lines: readonly string[], total: number, input: ChatExportInput, notes: number): string[][] {
    const groups: string[][] = [];
    let current: string[] = [];
    let size = bytesOf(header(1, total, input.generatedAt, notes, input.instructions));
    for (const line of lines) {
        const add = bytesOf(line) + 1;
        if (current.length > 0 && size + add > CHAT_EXPORT_PART_BYTES) {
            groups.push(current);
            current = [];
            size = bytesOf(header(groups.length + 1, total, input.generatedAt, notes, input.instructions));
        }
        current.push(line);
        size += add;
    }
    if (current.length > 0) groups.push(current);
    return groups;
}

/**
 * Build the file or files. Zero parts with `notes === 0` means nothing is in scope (the caller's
 * `export-nothing-in-scope`). Sizes are exact UTF-8 bytes including each part's own header: the part
 * count is found by iterating until the split made for that count produces that count.
 */
export function buildChatExport(input: ChatExportInput): ChatExportResult {
    const included = includedRecords(input.records, input.scope);
    if (included.length === 0) return { parts: [], notes: 0 };
    const notes = included.length;
    const lines = included.map((r) => capLine(noteLine(r, input.scope)));

    let total = 1;
    let groups = split(lines, total, input, notes);
    for (let i = 0; i < 6 && groups.length !== total; i++) {
        total = Math.max(total, groups.length);
        groups = split(lines, total, input, notes);
        if (groups.length < total) break; // a larger count never needs more parts; settle on the count we split for
    }
    total = groups.length;
    const finalGroups = split(lines, total, input, notes);
    const parts = finalGroups.map((group, i) => ({
        name: total === 1 ? `${CHAT_EXPORT_BASENAME}.md` : `${CHAT_EXPORT_BASENAME} (part ${i + 1} of ${total}).md`,
        text: `${header(i + 1, total, input.generatedAt, notes, input.instructions)}${group.join('\n')}\n`,
    }));
    return { parts, notes };
}

/** True when this text was written by a previous export (first line carries the marker). */
export function isOwnExport(text: string): boolean {
    const nl = text.indexOf('\n');
    return (nl === -1 ? text : text.slice(0, nl)).trim() === CHAT_EXPORT_MARKER;
}
