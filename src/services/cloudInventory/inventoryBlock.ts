/**
 * Inventory block: the generated section of a hub note that lists a paired Drive folder.
 *
 * The note belongs to the user; only the block between the markers belongs to the plugin:
 *
 *   <!-- aio:drive-inventory pair=<pairId> folder=<driveId> -->
 *   ...generated...
 *   <!-- /aio:drive-inventory pair=<pairId> folder=<driveId> -->
 *
 * Rules (all pure, all tested):
 *  - A rewrite needs exactly one start and one end marker for this pair and folder, in order and
 *    not nested. Anything else is a CONFLICT: nothing is written.
 *  - Text from Drive (file names, MIME types) is escaped for table cells and can never form a
 *    marker or an HTML comment.
 *  - The same listing renders to the same bytes. The block header keeps `hash`, `status` and
 *    `listed`; `listed` stays unchanged while the content hash does.
 */
import type { Result } from '../../core/result';
import { findMarkedBlock, replaceMarkedBlock } from '../../utils/ownedBlock';

export type Completeness = 'complete' | 'truncated';

export interface InventoryFile {
    id: string;
    name: string;
    mimeType: string;
    size: number | null;
    modifiedTime: string;
    md5Checksum?: string;
    sha256Checksum?: string;
    /** Folder path inside the paired root ('' for the root itself), names joined with `/` */
    path: string;
}

export interface InventoryListing {
    files: InventoryFile[];
    completeness: Completeness;
}

export interface BlockMeta {
    hash: string;
    status: Completeness;
    listed: string;
}

const compare = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);
const ID_PATTERN = /^[A-Za-z0-9_-]+$/;

/** Sorted copy of the files: by folder path, then id. */
export function sortedFiles(files: readonly InventoryFile[]): InventoryFile[] {
    return [...files].sort((a, b) => compare(a.path, b.path) || compare(a.id, b.id));
}

/** The text that is hashed into the content hash: sorted fields plus the completeness status. */
export function canonicalListing(listing: InventoryListing): string {
    const rows = sortedFiles(listing.files).map((f) =>
        [f.id, f.path, f.name, f.mimeType, f.size ?? '', f.modifiedTime, f.md5Checksum ?? '', f.sha256Checksum ?? ''].join('\u0000'),
    );
    return `${listing.completeness}\u0001${rows.join('\u0001')}`;
}

/** Escape text for a Markdown table cell or link label. Drive content can never form a marker. */
export function escapeCell(text: string): string {
    return text
        .replace(/\r?\n|\r|\t/g, ' ')
        .replaceAll('\\', '\\\\')
        .replaceAll('|', '\\|')
        .replaceAll('[', '\\[')
        .replaceAll(']', '\\]')
        .replaceAll('<', '&lt;')
        .replaceAll('>', '&gt;')
        .replaceAll('`', '\\`');
}

/** The one place a Drive file link is built. Opens in the Drive app on Android. */
export function driveFileLink(id: string): string | null {
    return ID_PATTERN.test(id) ? `https://drive.google.com/file/d/${id}/view` : null;
}

function humanSize(size: number | null): string {
    if (size === null || !Number.isFinite(size)) return '—';
    if (size < 1024) return `${size} B`;
    if (size < 1024 * 1024) return `${(size / 1024).toFixed(1)} KB`;
    if (size < 1024 * 1024 * 1024) return `${(size / (1024 * 1024)).toFixed(1)} MB`;
    return `${(size / (1024 * 1024 * 1024)).toFixed(1)} GB`;
}

function shortType(mime: string): string {
    if (mime.startsWith('application/vnd.google-apps.')) return mime.slice('application/vnd.google-apps.'.length);
    const slash = mime.indexOf('/');
    return slash === -1 ? mime : mime.slice(slash + 1);
}

export const START_PREFIX = '<!-- aio:drive-inventory ';
export const END_PREFIX = '<!-- /aio:drive-inventory ';

export function startMarker(pairId: string, folderId: string): string {
    return `${START_PREFIX}pair=${pairId} folder=${folderId} -->`;
}

export function endMarker(pairId: string, folderId: string): string {
    return `${END_PREFIX}pair=${pairId} folder=${folderId} -->`;
}

export interface RenderLabels {
    /** "Generated by AI Organiser — edits inside this block are overwritten." */
    notice: string;
    truncated: string;
    name: string;
    type: string;
    size: string;
    modified: string;
    empty: string;
}

/** Render the complete block, markers included. */
export function renderBlock(opts: {
    pairId: string;
    folderId: string;
    listing: InventoryListing;
    meta: BlockMeta;
    labels: RenderLabels;
}): string {
    const { pairId, folderId, listing, meta, labels } = opts;
    const lines: string[] = [startMarker(pairId, folderId)];
    lines.push(`> ${labels.notice}`);
    if (listing.completeness === 'truncated') lines.push(`> ${labels.truncated}`);
    lines.push(`<!-- aio:meta hash=${meta.hash} status=${meta.status} listed=${meta.listed} -->`);
    const files = sortedFiles(listing.files);
    if (files.length === 0) {
        lines.push('', labels.empty);
    } else {
        lines.push('', `| ${labels.name} | ${labels.type} | ${labels.size} | ${labels.modified} |`, '|---|---|---|---|');
        for (const f of files) {
            const label = escapeCell(f.path ? `${f.path}/${f.name}` : f.name);
            const link = driveFileLink(f.id);
            const name = link ? `[${label}](${link})` : label;
            lines.push(`| ${name} | ${escapeCell(shortType(f.mimeType))} | ${humanSize(f.size)} | ${escapeCell(f.modifiedTime.slice(0, 10))} |`);
        }
    }
    lines.push(endMarker(pairId, folderId));
    return lines.join('\n');
}

const META = /<!-- aio:meta hash=([0-9a-f]+) status=(complete|truncated) listed=(\S+) -->/;

/** Read the meta comment from a rendered block, or null when absent or malformed. */
export function parseBlockMeta(block: string): BlockMeta | null {
    const m = META.exec(block);
    return m ? { hash: m[1], status: m[2] as Completeness, listed: m[3] } : null;
}

export interface OwnedBlock {
    start: number;
    /** Index just after the end marker */
    end: number;
    text: string;
}

/**
 * Find this pair's block. `ok(null)` = there is none yet. `err('marker-conflict')` = the markers are
 * duplicated, missing one half, out of order or nested: do not write.
 */
export function findOwnedBlock(text: string, pairId: string, folderId: string): Result<OwnedBlock | null> {
    return findMarkedBlock(text, { start: startMarker(pairId, folderId), end: endMarker(pairId, folderId), nestedPrefixes: [START_PREFIX, END_PREFIX] });
}

/** Replace this pair's block, or append it. Returns the new note text. */
export function replaceBlock(text: string, block: string, pairId: string, folderId: string): Result<string> {
    return replaceMarkedBlock(text, block, { start: startMarker(pairId, folderId), end: endMarker(pairId, folderId), nestedPrefixes: [START_PREFIX, END_PREFIX] });
}
