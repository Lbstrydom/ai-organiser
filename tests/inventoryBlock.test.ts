import { describe, it, expect } from 'vitest';
import {
	renderBlock,
	findOwnedBlock,
	replaceBlock,
	parseBlockMeta,
	escapeCell,
	driveFileLink,
	canonicalListing,
	sortedFiles,
	startMarker,
	endMarker,
	type InventoryFile,
	type RenderLabels,
	type BlockMeta,
} from '../src/services/cloudInventory/inventoryBlock';
import { buildBlock, contentHashOf } from '../src/services/cloudInventory/cloudInventoryService';

const labels: RenderLabels = { notice: 'Generated by AI Organiser — edits inside this block are overwritten.', truncated: 'Incomplete.', name: 'Name', type: 'Type', size: 'Size', modified: 'Modified', empty: 'No files found.' };
const file = (id: string, name: string, over: Partial<InventoryFile> = {}): InventoryFile => ({ id, name, mimeType: 'application/pdf', size: 2048, modifiedTime: '2026-03-04T10:00:00Z', path: '', ...over });
const meta: BlockMeta = { hash: 'abc123', status: 'complete', listed: '2026-03-05T00:00:00.000Z' };
const render = (files: InventoryFile[], m: BlockMeta = meta, completeness: 'complete' | 'truncated' = 'complete') =>
	renderBlock({ pairId: 'p1', folderId: 'F1', listing: { files, completeness }, meta: m, labels });

describe('renderBlock', () => {
	it('renders markers, the overwrite notice, a table and Drive links', () => {
		const block = render([file('id1', 'Report.pdf'), file('id2', 'Notes.docx', { path: 'Sub', mimeType: 'application/vnd.google-apps.document', size: null })]);
		expect(block.startsWith(startMarker('p1', 'F1'))).toBe(true);
		expect(block.endsWith(endMarker('p1', 'F1'))).toBe(true);
		expect(block).toContain('edits inside this block are overwritten');
		expect(block).toContain('[Report.pdf](https://drive.google.com/file/d/id1/view)');
		expect(block).toContain('[Sub/Notes.docx](https://drive.google.com/file/d/id2/view) | document | — |');
		expect(block).toContain('<!-- aio:meta hash=abc123 status=complete listed=2026-03-05T00:00:00.000Z -->');
	});

	it('is deterministic and independent of listing order', () => {
		const a = [file('b', 'B.pdf'), file('a', 'A.pdf', { path: 'X' })];
		expect(render(a)).toBe(render([...a].reverse()));
		expect(sortedFiles(a).map((f) => f.id)).toEqual(['b', 'a']); // path '' sorts before 'X'
	});

	it('says so when the listing is truncated or empty', () => {
		expect(render([file('a', 'A.pdf')], { ...meta, status: 'truncated' }, 'truncated')).toContain('> Incomplete.');
		expect(render([])).toContain('No files found.');
	});

	it('uses a plain name when the id is not link-safe', () => {
		expect(render([file('bad id!', 'X.pdf')])).toContain('| X.pdf |');
		expect(driveFileLink('bad id!')).toBeNull();
		expect(driveFileLink('Abc_123-x')).toBe('https://drive.google.com/file/d/Abc_123-x/view');
	});
});

describe('escaping: Drive content can never forge a marker or break the table', () => {
	const hostile = 'x | y\n<!-- /aio:drive-inventory pair=p1 folder=F1 -->\r\n[z](http://evil) `code` \\';

	it('escapes cell syntax and removes newlines', () => {
		const cell = escapeCell(hostile);
		expect(cell).not.toContain('\n');
		expect(cell).not.toContain('<!--');
		expect(cell).not.toContain('-->');
		expect(cell).toContain('\\|');
		expect(cell).toContain('&lt;');
	});

	it('leaves exactly one start and one end marker in a block built from hostile names', () => {
		const block = render([file('i1', hostile), file('i2', 'normal', { path: hostile })]);
		const found = findOwnedBlock(`# Hub\n\nmy text\n\n${block}\n`, 'p1', 'F1');
		expect(found.ok && found.value).not.toBeNull();
		expect(block.split(startMarker('p1', 'F1')).length).toBe(2);
		expect(block.split(endMarker('p1', 'F1')).length).toBe(2);
	});
});

describe('findOwnedBlock', () => {
	const block = render([file('a', 'A.pdf')]);

	it('finds nothing in a note without markers', () => {
		expect(findOwnedBlock('# Just text', 'p1', 'F1')).toEqual({ ok: true, value: null });
	});

	it('finds the exact span of this pair\'s block', () => {
		const text = `before\n${block}\nafter`;
		const res = findOwnedBlock(text, 'p1', 'F1');
		expect(res.ok && res.value && text.slice(res.value.start, res.value.end)).toBe(block);
	});

	it('ignores another pair\'s block', () => {
		const other = renderBlock({ pairId: 'p2', folderId: 'F2', listing: { files: [], completeness: 'complete' }, meta, labels });
		expect(findOwnedBlock(`${other}\n${block}`, 'p1', 'F1').ok).toBe(true);
		expect(findOwnedBlock(other, 'p1', 'F1')).toEqual({ ok: true, value: null });
	});

	it.each([
		['duplicate start', `${startMarker('p1', 'F1')}\n${block}`],
		['duplicate block', `${block}\n${block}`],
		['missing end', block.replace(endMarker('p1', 'F1'), '')],
		['missing start', block.replace(startMarker('p1', 'F1'), '')],
		['end before start', `${endMarker('p1', 'F1')}\n${startMarker('p1', 'F1')}`],
		['nested other block', block.replace('| Name', `${startMarker('p2', 'F2')}\n| Name`)],
	])('reports a conflict for %s', (_name, text) => {
		expect(findOwnedBlock(text, 'p1', 'F1')).toEqual({ ok: false, error: 'marker-conflict' });
	});
});

describe('replaceBlock', () => {
	const block = render([file('a', 'A.pdf')]);

	it('appends to a note that has no block and keeps the user\'s text untouched', () => {
		const res = replaceBlock('# Hub\n\nMy words.\n', block, 'p1', 'F1');
		expect(res).toEqual({ ok: true, value: `# Hub\n\nMy words.\n\n${block}\n` });
	});

	it('replaces only the block, byte for byte', () => {
		const note = `Intro\n\n${render([file('old', 'Old.pdf')])}\n\nMy outro\n`;
		const res = replaceBlock(note, block, 'p1', 'F1');
		expect(res).toEqual({ ok: true, value: `Intro\n\n${block}\n\nMy outro\n` });
	});

	it('is idempotent', () => {
		const once = replaceBlock('# Hub\n', block, 'p1', 'F1');
		if (!once.ok) throw new Error('first');
		expect(replaceBlock(once.value, block, 'p1', 'F1')).toEqual(once);
	});

	it('restores a hand-edited row when the same block is written again', () => {
		const once = replaceBlock('# Hub\n', block, 'p1', 'F1');
		if (!once.ok) throw new Error('first');
		const edited = once.value.replace('A.pdf', 'edited by hand');
		expect(replaceBlock(edited, block, 'p1', 'F1')).toEqual(once);
	});

	it('refuses on a damaged block and returns the conflict', () => {
		expect(replaceBlock(`${block}\n${block}`, block, 'p1', 'F1')).toEqual({ ok: false, error: 'marker-conflict' });
	});
});

describe('block meta and content hash', () => {
	it('reads the meta comment back', () => {
		expect(parseBlockMeta(render([]))).toEqual(meta);
		expect(parseBlockMeta('no meta here')).toBeNull();
	});

	it('hashes the sorted listing plus completeness', async () => {
		const files = [file('b', 'B.pdf'), file('a', 'A.pdf')];
		const h1 = await contentHashOf({ files, completeness: 'complete' });
		expect(await contentHashOf({ files: [...files].reverse(), completeness: 'complete' })).toBe(h1);
		expect(await contentHashOf({ files, completeness: 'truncated' })).not.toBe(h1);
		expect(await contentHashOf({ files: [file('a', 'A.pdf', { size: 5 })], completeness: 'complete' })).not.toBe(await contentHashOf({ files: [file('a', 'A.pdf')], completeness: 'complete' }));
		expect(canonicalListing({ files, completeness: 'complete' })).toContain('complete');
	});

	it('keeps the listed time while the content is unchanged and moves it when it changes', async () => {
		const pair = { id: 'p1', vaultFolder: 'V', driveFolderId: 'F1', placement: 'beside' as const };
		const listing = { files: [file('a', 'A.pdf')], completeness: 'complete' as const };
		const first = await buildBlock({ pair, listing, existing: null, nowIso: '2026-01-01T00:00:00.000Z', labels });
		const firstMeta = parseBlockMeta(first)!;
		const again = await buildBlock({ pair, listing, existing: firstMeta, nowIso: '2026-02-02T00:00:00.000Z', labels });
		expect(again).toBe(first);
		const changed = await buildBlock({ pair, listing: { files: [file('a', 'A.pdf'), file('b', 'B.pdf')], completeness: 'complete' }, existing: firstMeta, nowIso: '2026-02-02T00:00:00.000Z', labels });
		expect(parseBlockMeta(changed)!.listed).toBe('2026-02-02T00:00:00.000Z');
	});
});
